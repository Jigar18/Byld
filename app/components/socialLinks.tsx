export const toSocialLinks = (record: Partial<Record<string, string | null>>): SocialLink[] =>
  SOCIAL_PLATFORMS.flatMap((platform) => {
    const url = record[platform];
    return url ? [{ platform, url }] : [];
  });

const platformNames: Partial<Record<SocialPlatform, string>> = {
  linkedin: "LinkedIn",
  github: "GitHub",
  leetcode: "LeetCode",
  youtube: "YouTube",
  hackerrank: "HackerRank",
};

export const platformLabel = (platform: SocialPlatform) =>
  platformNames[platform] ?? platform.charAt(0).toUpperCase() + platform.slice(1);

// Saved links are only ever opened as web or mail links, whatever text was stored.
export const socialLinkHref = ({ platform, url }: SocialLink) => {
  if (platform === "email") return `mailto:${url.replace(/^mailto:/i, "")}`;
  return /^https?:\/\//i.test(url) ? url : null;
};

export const displaySocialLink = ({ url }: SocialLink) =>
  url.replace(/^(mailto:|https?:\/\/)(www\.)?/i, "").replace(/\/$/, "");

export function SocialIcon({ platform, className = "size-5" }: { platform: SocialPlatform; className?: string }) {
  const { path, outline } = socialIcons[platform];
  return outline ? (
    <svg aria-hidden="true" xmlns="http://www.w3.org/2000/svg" fill="none" viewBox="0 0 24 24" strokeWidth="1.5" stroke="currentColor" className={className}>
      <path strokeLinecap="round" strokeLinejoin="round" d={path} />
    </svg>
  ) : (
    <svg aria-hidden="true" viewBox="0 0 24 24" xmlns="http://www.w3.org/2000/svg" className={className}>
      <path fill="currentColor" d={path} />
    </svg>
  );
}
